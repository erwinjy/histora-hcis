    QUEUED="QUEUED"; RUNNING="RUNNING"; SUCCEEDED="SUCCEEDED"; FAILED="FAILED"
    CANCELLED="CANCELLED"; DEGRADED="DEGRADED"; BLOCKED_EXTERNAL="BLOCKED_EXTERNAL"
    BLOCKED_PRIVACY_POLICY="BLOCKED_PRIVACY_POLICY"; BLOCKED_BUDGET_POLICY="BLOCKED_BUDGET_POLICY"

