from enum import StrEnum

class FactStatus(StrEnum):
    VERIFIED="VERIFIED"; PROBABLE="PROBABLE"; DISPUTED="DISPUTED"
    POSSIBLE="POSSIBLE"; UNSUPPORTED="UNSUPPORTED"; UNKNOWN="UNKNOWN"

class ClaimEpistemicStatus(StrEnum):
    ASSERTED="ASSERTED"; REPORTED="REPORTED"; RUMORED="RUMORED"
    INFERRED="INFERRED"; DENIED="DENIED"; UNCERTAIN="UNCERTAIN"

class MissingnessStatus(StrEnum):
    ABSENT="ABSENT"; UNKNOWN="UNKNOWN"; NOT_RECORDED="NOT_RECORDED"
    LOST_SOURCE="LOST_SOURCE"; UNOBSERVABLE="UNOBSERVABLE"
    PARTIALLY_OBSERVED="PARTIALLY_OBSERVED"

